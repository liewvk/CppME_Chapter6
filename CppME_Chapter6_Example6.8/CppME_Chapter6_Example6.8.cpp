#include <iostream>
using namespace std;

int main()
{
    int marks = 75;

    cout << "marks == 75 : " << (marks == 75) << endl;
    cout << "marks != 50 : " << (marks != 50) << endl;
    cout << "marks > 60  : " << (marks > 60) << endl;
    cout << "marks < 40  : " << (marks < 40) << endl;
    cout << "marks >= 75 : " << (marks >= 75) << endl;
    cout << "marks <= 80 : " << (marks <= 80) << endl;

    return 0;
}
