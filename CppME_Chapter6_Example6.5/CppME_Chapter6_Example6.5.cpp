#include <iostream>
using namespace std;

int main()
{
    int num1 = 15;
    int num2 = 4;

    cout << "Number 1   = " << num1 << endl;
    cout << "Number 2   = " << num2 << endl;
    cout << "Addition   = " << num1 + num2 << endl;
    cout << "Subtraction= " << num1 - num2 << endl;
    cout << "Multiply   = " << num1 * num2 << endl;
    cout << "Division   = " << num1 / num2 << endl;
    cout << "Remainder  = " << num1 % num2 << endl;

    return 0;
}
